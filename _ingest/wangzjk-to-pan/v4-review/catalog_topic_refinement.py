def refined_topic(title, received):
    """Use specific actions and objects before considering the format of the entry."""
    for text in (title, received):
        if not text:
            continue
        for category,sub,pattern in _PATTERNS:
            if pattern.search(text):
                return category,sub
    return '', ''


def reference_topic(title, received):
    """Group accessible reference entries by what the publisher actually offers."""
    if _SITE_NOTE.search(title):
        return 'reference','站点说明'
    lead = title + ' ' + received[:220]
    if _PROJECT.search(lead) and _PROJECT_PURPOSE.search(lead):
        return 'reference','项目线索'
    if _READING.search(title):
        return 'reference','经验与阅读'
    if _PACK.search(title) or re.search(r'^\s*(?:课程|学习)(?:介绍|目录|大纲)', received):
        return 'reference','课程与资料'
    if _OPERATIONS.search(title):
        return 'reference','操作方法'
    return '', ''
